"""Record versions from the tested environment for the declared dependency closure."""
import importlib.metadata as metadata
import tomllib
from pathlib import Path
from packaging.requirements import Requirement
from packaging.utils import canonicalize_name

project = tomllib.loads(Path('pyproject.toml').read_text(encoding='utf-8'))['project']
queue = [Requirement(r) for r in project['dependencies'] + project['optional-dependencies']['test']]
seen, versions = set(), {}
while queue:
    req = queue.pop()
    key = (canonicalize_name(req.name), tuple(sorted(req.extras)))
    if key in seen:
        continue
    seen.add(key)
    distribution = metadata.distribution(req.name)
    versions[distribution.metadata['Name']] = distribution.version
    for raw in distribution.requires or []:
        child = Requirement(raw)
        if child.marker is None or any(child.marker.evaluate({'extra': extra}) for extra in (req.extras or {''})):
            queue.append(child)
Path('constraints.txt').write_text('# Tested dependency versions, generated by scripts/lock_dependencies.py\n' +
    '\n'.join(f'{name}=={version}' for name, version in sorted(versions.items(), key=lambda pair: pair[0].lower())) + '\n', encoding='utf-8')
print(f'Locked {len(versions)} declared/transitive dependencies')
